def get_menu_text() -> str:
    """Полный текст меню для контекста ИИ."""
    lines = [CAFE_INFO, "\n=== МЕНЮ ==="]
    for cat, items in MENU.items():
        lines.append(f"\n{cat}:")
        for item in items:
            lines.append(f"  - {item['name']} ({item['desc']}) — {item['price']} ₽")
    return "\n".join(lines)


